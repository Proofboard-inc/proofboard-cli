// Command homebrew_formula writes Formula/proofboard.rb for the
// Proofboard-inc/homebrew-tap repository from a release's binaries.
//
//	go run ./scripts/homebrew_formula vX.Y.Z DIR > Formula/proofboard.rb
//
// DIR holds the four product-named executables the release publishes for
// macOS and Linux. The formula points at those release-signed binaries
// rather than building from source, because the CLI verifies the release
// signature when it self-updates and a Homebrew-compiled binary would not
// carry one.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// homebrewAssets are the release assets the formula installs, in the order
// render reads them. They must match scripts/release_assets.sh binaries.
var homebrewAssets = []string{
	"Proofboard-Career-Agent-darwin-arm64",
	"Proofboard-Career-Agent-darwin-amd64",
	"Proofboard-Career-Agent-linux-amd64",
	"Proofboard-Career-Agent-linux-arm64",
}

var releaseTag = regexp.MustCompile(`^v(\d+\.\d+\.\d+)$`)

const formulaTemplate = `# Proofboard Career Agent — https://github.com/Proofboard-inc/proofboard-cli
#
# Generated by the release workflow (scripts/homebrew_formula) for each tagged
# release; edit the generator, not this file.
#
# Distributed as prebuilt, release-signed binaries rather than built from
# source: the release workflow signs each binary with the project's release
# key and the CLI verifies that signature when self-updating, so a
# Homebrew-compiled binary would not carry a signature the updater accepts.
class Proofboard < Formula
  desc "Proofboard Career Agent - builds your engineering career record locally"
  homepage "https://github.com/Proofboard-inc/proofboard-cli"
  version "{{VERSION}}"
  license "MIT"

  on_macos do
    on_arm do
      url "{{URL:Proofboard-Career-Agent-darwin-arm64}}"
      sha256 "{{SHA:Proofboard-Career-Agent-darwin-arm64}}"
    end
    on_intel do
      url "{{URL:Proofboard-Career-Agent-darwin-amd64}}"
      sha256 "{{SHA:Proofboard-Career-Agent-darwin-amd64}}"
    end
  end

  on_linux do
    on_intel do
      url "{{URL:Proofboard-Career-Agent-linux-amd64}}"
      sha256 "{{SHA:Proofboard-Career-Agent-linux-amd64}}"
    end
    # Single-board machines and ARM cloud instances. The release publishes a
    # linux-arm64 build, so refusing it here would describe the tap rather
    # than the tool.
    on_arm do
      url "{{URL:Proofboard-Career-Agent-linux-arm64}}"
      sha256 "{{SHA:Proofboard-Career-Agent-linux-arm64}}"
    end
  end

  def install
    bin.install Dir["Proofboard-Career-Agent-*"].first => "proofboard"
  end

  def caveats
    <<~EOS
      Start the background Career Agent with:
        proofboard install

      Homebrew manages the executable, so use ` + "`brew upgrade proofboard`" + `
      rather than ` + "`proofboard update`" + ` to move between versions.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/proofboard version")
  end
end
`

// render returns the formula for release tag (vX.Y.Z) using the binaries in dir.
func render(tag, dir string) (string, error) {
	m := releaseTag.FindStringSubmatch(tag)
	if m == nil {
		return "", fmt.Errorf("release tag %q is not of the form vX.Y.Z", tag)
	}
	out := strings.ReplaceAll(formulaTemplate, "{{VERSION}}", m[1])
	for _, name := range homebrewAssets {
		sum, err := sha256File(filepath.Join(dir, name))
		if err != nil {
			return "", fmt.Errorf("checksum %s: %w", name, err)
		}
		url := "https://github.com/Proofboard-inc/proofboard-cli/releases/download/" + tag + "/" + name
		out = strings.ReplaceAll(out, "{{URL:"+name+"}}", url)
		out = strings.ReplaceAll(out, "{{SHA:"+name+"}}", sum)
	}
	return out, nil
}

func sha256File(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run ./scripts/homebrew_formula vX.Y.Z DIR > Formula/proofboard.rb")
		os.Exit(2)
	}
	formula, err := render(os.Args[1], os.Args[2])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Print(formula)
}
